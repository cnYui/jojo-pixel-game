# 招牌用的小号像素英文字（3 × 5）：点阵中文字库缩到 10 px 以下英文会糊，店招、车牌这些自己点。
GLYPH = {
    'A': '010101111101101', 'B': '110101110101110', 'C': '011100100100011', 'D': '110101101101110', 'E': '111100110100111',
    'F': '111100110100100', 'G': '011100101101011', 'H': '101101111101101', 'I': '111010010010111', 'J': '001001001101010',
    'K': '101101110101101', 'L': '100100100100111', 'M': '101111111101101', 'N': '110101101101101', 'O': '010101101101010',
    'P': '110101110100100', 'Q': '010101101111011', 'R': '110101110101101', 'S': '011100010001110', 'T': '111010010010010',
    'U': '101101101101111', 'V': '101101101101010', 'W': '101101111111101', 'X': '101101010101101', 'Y': '101101010010010',
    'Z': '111001010100111', '0': '111101101101111', '1': '010110010010111', '2': '110001010100111', '3': '110001010001110',
    '4': '101101111001001', '5': '111100110001110', '6': '111100111101111', '7': '111001010010010', '8': '111101111101111',
    '9': '111101111001111', ' ': '000000000000000', '-': '000000111000000', '.': '000000000000010', '!': '010010010000010',
    ':': '000010000010000', "'": '010010000000000', '/': '001001010100100', '&': '010101010101011', '+': '000010111010000',
}


def ptext(cv, x, y, s, c, scale=1, gap=1, shadow=None):
    """在 (x, y) 写一行 3 × 5 像素字（scale 放大倍数）；返回文字宽度"""
    cx = x
    for ch in s.upper():
        g = GLYPH.get(ch, GLYPH[' '])
        for i, bit in enumerate(g):
            if bit == '1':
                px, py = cx + (i % 3) * scale, y + (i // 3) * scale
                if shadow:
                    cv.rect(px + 1, py + 1, px + scale, py + scale, shadow)
                cv.rect(px, py, px + scale - 1, py + scale - 1, c)
        cx += (3 + gap) * scale
    return cx - x - gap * scale
